TYPES={"ACCESS_RESTRICTED","MISSING_DISAGGREGATION","DEFINITION_MISMATCH","TIME_MISMATCH","GEOGRAPHY_MISMATCH","INCOMPATIBLE_UNIT_OR_DENOMINATOR","COLLECTION_CAPACITY_CONSTRAINT","LANGUAGE_OR_COMMUNICATION_BARRIER","INSTITUTIONAL_COORDINATION_BARRIER","UNKNOWN_BARRIER"}
def validate_barrier(kind):
    if kind not in TYPES: raise ValueError(f"Unknown barrier type: {kind}")
    return kind
